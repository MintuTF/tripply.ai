#!/usr/bin/env node
// Bundles every migration, in dependency order, into supabase/setup.sql so a new Supabase project
// can be set up by pasting ONE file into the SQL editor.   Run: node scripts/build-supabase-setup.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src/lib/db/migrations');

// Explicit order: some numbers are shared (001, 002), and the admin schema needs the users table first.
const ORDER = [
  '001_initial_schema.sql',
  '001_admin_schema.sql',
  '002_add_trip_status.sql',
  '002_trip_invitations.sql',
  '002_welcome_email.sql',
  '003_user_sync_trigger.sql',
  '004_add_comments_reactions.sql',
  '005_user_creation_trigger.sql',
  '006_add_researching_status.sql',
  '007_chat_conversations.sql',
  '008_add_itinerary_fields.sql',
  '009_city_videos_cache.sql',
  '010_saved_places.sql',
  '011_security_fixes.sql',
  '012_video_insights_cache.sql',
];

const header = `-- Tripply database setup (generated by scripts/build-supabase-setup.mjs - do not edit by hand).
-- For a NEW, empty Supabase project: paste this whole file into SQL Editor and run it once.
-- To change the schema later, add a new numbered file in src/lib/db/migrations and run the script again.
`;

const body = ORDER.map((file) => `\n-- ============================================================\n-- ${file}\n-- ============================================================\n${readFileSync(join(dir, file), 'utf8').trim()}\n`).join('');
writeFileSync(join(root, 'supabase/setup.sql'), header + body);
console.log(`Wrote supabase/setup.sql from ${ORDER.length} migrations`);
